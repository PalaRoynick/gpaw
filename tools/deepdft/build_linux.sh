#!/usr/bin/env bash
# Build this checkout and its optional DeepDFT stack, then verify readiness.
set -euo pipefail
root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd)
mode=cpu
python_bin=python3
venv_dir=
state_dir=
sysroot=
mpi_ranks=2
while (($#)); do
    case "$1" in
        --mode) mode=${2:?}; shift 2 ;;
        --python) python_bin=${2:?}; shift 2 ;;
        --env) venv_dir=${2:?}; shift 2 ;;
        --state-dir) state_dir=${2:?}; shift 2 ;;
        --sysroot) sysroot=${2:?}; shift 2 ;;
        --mpi-ranks) mpi_ranks=${2:?}; shift 2 ;;
        --help)
            echo 'Usage: build_linux.sh [--mode cpu|v100] [--python python3]'
            echo '       [--env DIR] [--state-dir DIR] [--sysroot DIR] [--mpi-ranks N]'
            echo 'Install OS packages first with install_system_deps.sh (explicit sudo).'
            echo 'Requires the DeepDFT branch. Builds GPAW/ASAP3 from source and runs checks.'
            exit 0 ;;
        *) echo "Unknown argument: $1" >&2; exit 2 ;;
    esac
done
[[ $mode == cpu || $mode == v100 ]] || { echo 'Mode must be cpu or v100.' >&2; exit 2; }
[[ $mpi_ranks =~ ^[1-9][0-9]*$ ]] || { echo 'Invalid MPI rank count.' >&2; exit 2; }
[[ $(uname -m) == x86_64 ]] || { echo 'This pinned wheel profile requires x86_64.' >&2; exit 1; }
"$python_bin" - <<'PY'
import sys
assert (3, 11) <= sys.version_info[:2] <= (3, 13), 'Use Python 3.11, 3.12 or 3.13'
PY
for cmd in git mpicxx mpiexec timeout; do
    command -v "$cmd" >/dev/null || { echo "Missing $cmd; install system prerequisites." >&2; exit 1; }
done
[[ $(git -C "$root" branch --show-current) == DeepDFT ]] || {
    echo 'Check out the DeepDFT branch before building.' >&2; exit 1;
}
if [[ $mode == v100 ]]; then
    command -v nvidia-smi >/dev/null || { echo 'Install an NVIDIA driver first.' >&2; exit 1; }
    nvidia-smi
fi
venv_dir=${venv_dir:-$root/venv-deepdft-$mode}
state_dir=${state_dir:-$root/.deepdft-build/$mode}
mkdir -p "$state_dir"
state_dir=$(cd "$state_dir" && pwd)
venv_dir=$("$python_bin" -c 'import os,sys; print(os.path.abspath(sys.argv[1]))' "$venv_dir")
if [[ -n $sysroot ]]; then sysroot=$(cd "$sysroot" && pwd); fi
exec > >(tee "$state_dir/build.log") 2>&1
echo "Building $root; mode=$mode; environment=$venv_dir"
# Never erase or adopt an unrelated existing environment.
if [[ -e $venv_dir && ! -f $venv_dir/.gpaw-deepdft-managed ]]; then
    echo 'Environment path already exists and is not managed by this script; choose --env.' >&2
    exit 1
fi
if [[ ! -d $venv_dir ]]; then
    "$python_bin" -m venv "$venv_dir"
    printf '%s\n' "$mode" > "$venv_dir/.gpaw-deepdft-managed"
fi
[[ $(cat "$venv_dir/.gpaw-deepdft-managed") == "$mode" ]] || {
    echo 'Use different environment paths for cpu and v100.' >&2; exit 1;
}
export PIP_CACHE_DIR="$state_dir/pip-cache"
export XDG_CACHE_HOME="$state_dir/cache"
export MPLCONFIGDIR="$state_dir/matplotlib"
export PYTHONDONTWRITEBYTECODE=1
export OMP_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1
unset GPAW_MPI_OPTIONS GPAW_MPI_BACKEND
export GPAW_CONFIG="$state_dir/siteconfig.py"
"$venv_dir/bin/python" - "$GPAW_CONFIG" "$sysroot" <<'PY'
from pathlib import Path
import sys
path, prefix = sys.argv[1:]
config = """# Generated by tools/deepdft/build_linux.sh
mpi = True
compiler = 'mpicxx'
libraries = ['blas', 'xc', 'fftw3', 'scalapack-openmpi']
fftw = True
scalapack = True
noblas = False
nolibxc = False
extra_compile_args += ['-O2']
"""
if prefix:
    p = Path(prefix) / 'usr'
    inc = [str(p / 'include'), str(p / 'lib/x86_64-linux-gnu/openmpi/include')]
    lib = [str(p / 'lib/x86_64-linux-gnu'), str(p / 'lib/x86_64-linux-gnu/blas')]
    config += f'include_dirs = {inc!r}\nlibrary_dirs = {lib!r}\nruntime_library_dirs = {lib!r}\n'
Path(path).write_text(config)
PY
if [[ -n $sysroot ]]; then
    export CPLUS_INCLUDE_PATH="$sysroot/usr/include:$sysroot/usr/lib/x86_64-linux-gnu/openmpi/include${CPLUS_INCLUDE_PATH:+:$CPLUS_INCLUDE_PATH}"
    export LIBRARY_PATH="$sysroot/usr/lib/x86_64-linux-gnu:$sysroot/usr/lib/x86_64-linux-gnu/blas${LIBRARY_PATH:+:$LIBRARY_PATH}"
fi
# Diagnose missing headers/link libraries before expensive Python/C++ builds.
cat > "$state_dir/prerequisites.cpp" <<'CPP'
#include <mpi.h>
#include <xc.h>
#include <fftw3.h>
int main() { int a, b; MPI_Get_version(&a, &b); xc_version(&a, &b, &a);
    void* p = fftw_malloc(16); fftw_free(p); return 0; }
CPP
mpicxx "$state_dir/prerequisites.cpp" -o "$state_dir/prerequisites" \
    -lxc -lfftw3 -lblas -lscalapack-openmpi
cd "$root"
git submodule update --init --recursive
git submodule status > "$state_dir/submodules.txt"
"$venv_dir/bin/python" -m pip install 'pip==25.1.1' 'setuptools==80.9.0' \
    'wheel==0.45.1' 'pybind11==3.0.1' 'numpy==2.2.6'
torch_index=https://download.pytorch.org/whl/cpu
if [[ $mode == v100 ]]; then torch_index=https://download.pytorch.org/whl/cu118; fi
"$venv_dir/bin/python" -m pip install 'torch==2.7.1' --index-url "$torch_index"
# ASAP3 and GPAW are compiled against this environment's NumPy and toolchain.
"$venv_dir/bin/python" -m pip install --no-build-isolation --no-binary=asap3 \
    -r tools/deepdft/requirements-linux.txt
"$venv_dir/bin/python" -m pip install --no-build-isolation -e '.[deepdft]'
"$venv_dir/bin/python" -m pip check
"$venv_dir/bin/python" - "$state_dir/activate.sh" "$venv_dir" "$state_dir" <<'PY'
from pathlib import Path
from shlex import quote
import sys
out, venv, state = sys.argv[1:]
lines = [f'source {quote(venv + "/bin/activate")}',
         f'export GPAW_CONFIG={quote(state + "/siteconfig.py")}',
         f'export XDG_CACHE_HOME={quote(state + "/cache")}',
         f'export MPLCONFIGDIR={quote(state + "/matplotlib")}',
         'export OMP_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 PYTHONDONTWRITEBYTECODE=1',
         'unset GPAW_MPI_OPTIONS GPAW_MPI_BACKEND']
Path(out).write_text('\n'.join(lines) + '\n')
PY
"$venv_dir/bin/python" -m pip freeze > "$state_dir/python-packages.txt"
git rev-parse HEAD > "$state_dir/gpaw-commit.txt"
git status --short > "$state_dir/source-status.txt"
bash tools/deepdft/check_linux.sh --state-dir "$state_dir" --mode "$mode" --mpi-ranks "$mpi_ranks"
echo "Build and checks passed. Activate with: source '$state_dir/activate.sh'"
