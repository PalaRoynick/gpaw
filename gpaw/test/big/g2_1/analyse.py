from ase.data.g2_1 import atom_names, molecule_names
from ase.io import read


def read_results() -> tuple[dict[str, float], dict[str, float]]:
    eatoms = {}
    eatomizations = {}
    distances = {}
    for name in atom_names + molecule_names:
        atoms = read(f'{name}.txt')
        e = atoms.get_potential_energy()
        if len(atoms) == 1:
            eatoms[name] = e
        else:
            for symbol in atoms.symbols:
                e -= eatoms[symbol]
            eatomizations[name] = -e / len(atoms)
            distances[name] = ((atoms.positions[-1] -
                                atoms.positions[0])**2).sum()**0.5
    return eatomizations, distances


