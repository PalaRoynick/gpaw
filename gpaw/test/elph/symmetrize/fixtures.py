def create_cache(path) -> MultiFileJSONCache:
    """Write the fixture data as a MultiFileJSONCache at *path*."""
    cache = MultiFileJSONCache(path)
    with cache.lock('info') as handle:
        if handle is not None:
            handle.save(dict(INFO))
    for key, F_av in FORCES.items():
        with cache.lock(key) as handle:
            if handle is not None:
                handle.save({'forces': np.array(F_av),
                             'dH_all_asp': {a: np.array(arr)
                                            for a, arr
                                            in DH_ALL_ASP[key].items()}})
    return cache
