def eos(atoms: Atoms,
        npoints: int = 7,
        maxstrain: float = 0.02) -> dict:
    """Do EOS calculation and fit result."""
    cell_cv = atoms.get_cell()

    energies = []
    strains = np.linspace(-maxstrain, maxstrain, npoints)
    for i, strain in enumerate(strains):
        atoms.set_cell((1.0 + strain) * cell_cv, scale_atoms=True)
        e = atoms.get_potential_energy()
        energies.append(e)

    strain0, e0, d2eds2 = fit(strains, energies)
    v0 = abs(np.linalg.det(cell_cv))
    volume = v0 * (1 + strain0)**3

    return dict(
        volume=volume,
        strains=strains.tolist(),
        energies=energies,
        energy=e0,
        strain=strain0,
        d2eds2=d2eds2)


def fit(strains: np.ndarray,
        energies: np.ndarray | list[float]) -> tuple[float, float, float]:
    """Fit energies.

    ::

                    3
                   ---   n        1
     f(s) = p(x) = >  c x,  x = -----,
                   --- n        1 + s
                   n=0

     df/ds = dp/dx dx/ds,

      2    2   2    2       2
     d f/ds = d p/dx (dx/ds).

    """

    x = 1 / (1 + strains)
    p0 = np.poly1d(np.polyfit(x, energies, 3))
    p1 = np.polyder(p0, 1)
    p2 = np.polyder(p1, 1)
    for x0 in np.roots(p1):
        if isinstance(x0, float) and x0 > 0 and p2(x0) > 0:
            break
    else:  # no break
        raise ValueError
    strain = 1 / x0 - 1
    e0 = p0(x0)
    d2eds2 = p2(x0) * x0**2
    return strain, e0, d2eds2


def run_eos_calculation(structure: str,
                        symbol: str,
                        tag: str = '',
                        **params) -> dict:
    """Create GPAW calculator and do EOS calculation."""
    atoms = reference_structure(symbol, structure)
    builder = Parameters(**params).dft_component_builder(atoms, log=None)
    params['kpts'] = builder.ibz.bz.size_c  # type: ignore
    params['gpts'] = builder.grid.size
    params.pop('h', None)
    if tag:
        tag += '-'
    atoms.calc = GPAW(txt=f'{tag}{structure}.txt', **params)
    data = eos(atoms)
    return data


def workflow() -> None:
    """Submit PW and LCAO calculations.

    101 PAW-potentials, 10 crystals, PW and LCAO: 2020 calculations.
    """
    from myqueue.workflow import run
    symbol, _, setup_name = Path().absolute().name.partition('.')
    for x in acwf_structures:
        run(function=work, args=[x, symbol, setup_name, 'pw', 'pw'],
            cores=24, tmax='1h', name=f'pw-{x}')
        run(function=work, args=[x, symbol, setup_name, 'lcao', 'lcao'],
            cores=24, tmax='5h', name=f'lcao-{x}', restart=2)


def work(structure: str,
         symbol: str,
         setup_name: str = '',
         mode: str = 'pw',
         tag: str = '',
         *,
         backwards_compatible=True,
         world=None):
    """Do single EOS calculations with PBE."""
    world = normalize_communicator(world)
    params: dict[str, Any] = dict(
        xc='PBE',
        occupations=dict(name='fermi-dirac', width=0.0612),
        kpts=dict(density=6.0),
        convergence=dict(density=1e-6))
    if mode == 'pw':
        params['mode'] = dict(name='pw', ecut=1000)
    else:
        params['mode'] = 'lcao'
        params['basis'] = 'dzp'
        params['h'] = 0.12
    if setup_name:
        params['setups'] = {symbol: setup_name}
    data = run_eos_calculation(
        structure,
        symbol,
        tag,
        **params)
    if world.rank == 0:
        if tag:
            tag += '-'
        Path(f'{tag}{structure}.json').write_text(
            json.dumps(data, indent=1))


def create_folders() -> None:
    """Create folder for all 101 PAW-potentials."""
    for name in all_names:
        Path(name).mkdir(exist_ok=True)


def collect_data() -> None:
    """Collect everything we need for a table on the web-page."""
    results = {}
    for name in all_names:
        result: dict[str, list[tuple[str, float]]] = {'pw': [], 'lcao': []}
        for mode in ['pw', 'lcao']:
            for path in Path(name).glob(f'{mode}-*.json'):
                structure = path.stem.split('-')[1]
                strain = json.loads(path.read_text())['strain']
                result[mode].append((structure, strain))
        results[name] = result
    Path('acwf-results.json').write_text(json.dumps(results))


def _energies(p: Path) -> dict[str, list[float]]:
    """Read Wien2k "formation" energies.

    Files:

      results-unaries-verification-PBE-v1-wien2k-dk_0.06.json
      results-oxides-verification-PBE-v1-wien2k-dk_0.06.json

    from the folder:

      ACWF-verification-data-and-scripts/
        acwf-verification-scripts/acwf_paper_plots/
          code-data/
    """
    d = json.loads(p.read_text())['BM_fit_data']
    D: dict[str, dict] = {}
    for k, v in d.items():
        s, name = k.split('-')
        if s not in D:
            D[s] = {}
        D[s][name] = v['E0']
    p = p.with_name(p.name.replace('oxides', 'unaries'))
    d = json.loads(p.read_text())['BM_fit_data']
    for k, v in d.items():
        s, name = k.split('/')
        s = s.split('-')[0]
        D[s][name] = v['E0']
    d = {}
    for s, v in D.items():
        if s == 'O':
            v['XO'] *= 2
            v['X2O5'] *= 2
        ex = v['FCC']
        eo = v['XO'] - ex
        d[s] = [v['Diamond'] / 2 - ex,
                v['SC'] - ex,
                v['BCC'] - ex,
                (v['XO3'] - ex - 3 * eo) / 4,
                (v['X2O3'] / 2 - 2 * ex - 3 * eo) / 5,
                (v['XO2'] - ex - 2 * eo) / 3,
                (v['X2O5'] / 2 - 2 * ex - 5 * eo) / 7,
                (v['X2O'] - 2 * ex - eo) / 3]
    return d


def check(dir: Path, silent=True) -> float:
    d = []
    v = {}
    for p in dir.glob('*.json'):
        name = p.stem.split('-')[-1]
        if name[0].islower():
            continue
        data = json.loads(p.read_text())
        x = data['strain']
        d.append(x * 100)
        e = data['energy']
        v[name] = e

    n = len(d)
    if n == 0:
        return np.nan
    mean = sum(d) / n
    meanabs = sum([abs(s) for s in d]) / n
    rms = (sum([s**2 for s in d]) / n)**0.5
    maxabs = max([abs(s) for s in d])

    if n == 10:
        ex = v['FCC']
        eo = v['XO'] - ex
        E = [v['Diamond'] / 2 - ex,
             v['SC'] - ex,
             v['BCC'] - ex,
             (v['XO3'] - ex - 3 * eo) / 4,
             (v['X4O6'] - 4 * ex - 6 * eo) / 10,
             (v['XO2'] - ex - 2 * eo) / 3,
             (v['X4O10'] - 4 * ex - 10 * eo) / 14,
             (v['X2O'] - 2 * ex - eo) / 3]
        symbol = dir.stem.split('.')[0]
        dE = np.array(E) - ENERGIES[symbol]
        ee = abs(dE).max()
    else:
        ee = np.nan

    if not silent:
        print(f'{dir.name:25} {n:2}',
              f'{mean:+7.2f} % {meanabs:7.2f} % {rms:7.2f} % {maxabs:7.2f} %',
              f'{ee:8.3f} eV')

    return maxabs, ee


def main():
    import sys
    results = []
    for x in sys.argv[1:]:
        e = check(Path(x), silent=False)
        results.append((e, x))
    for e, x in sorted(results):
        print(f'{e:7.2f} {x}')


def reference_structure(symbol: str,
                        name: str) -> Atoms:
    """Create one of the ACWF structures with the WIEN2K volume."""
    atoms = acwf_structures[name].copy()
    x = (volumes[symbol][name] / atoms.get_volume())**(1 / 3)
    if symbol == 'O' and name in ['X4O10', 'XO']:
        x *= 2**(1 / 3)
    atoms.set_cell(atoms.cell * x, scale_atoms=True)
    atoms.numbers[atoms.numbers == 0] = atomic_numbers[symbol]
    return atoms


